import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "64748B",
};

export const generatePpt = async (data) => {
  try {
    const ppt = new pptxgen();

    ppt.layout = "LAYOUT_WIDE";
    ppt.title = data.title || "CortexAI Presentation";
    ppt.subject = data.title || "CortexAI Presentation";
    ppt.company = "CortexAI";

    ppt.theme = {
      headFontFace: "Aptos",
      bodyFontFace: "Aptos",
      lang: "en-US",
    };

    addCover(ppt, data);

    const slides = Array.isArray(data?.slides) ? data.slides : [];

    slides.forEach((slideData, index) => {
      addContentSlide(
        ppt,
        slideData.title || `Slide ${index + 1}`,
        Array.isArray(slideData.points) ? slideData.points : [],
        index + 2,
        slides.length + 2
      );
    });

    addThankYou(ppt);

    return ppt;
  } catch (error) {
    console.error("PowerPoint generation failed:", error);
    throw error;
  }
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.primary,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.333,
    h: 0.18,
    fill: { color: "60A5FA" },
    line: { color: "60A5FA" },
  });

  slide.addText(data.title || "CortexAI Presentation", {
    x: 0.7,
    y: 1.7,
    w: 12,
    h: 1,
    align: "center",
    valign: "mid",
    color: COLORS.white,
    bold: true,
    fontFace: "Aptos Display",
    fontSize: 30,
    breakLine: false,
    fit: "shrink",
  });

  slide.addText(data.subtitle || "AI-Generated Presentation", {
    x: 1,
    y: 2.9,
    w: 11.3,
    h: 0.7,
    align: "center",
    valign: "mid",
    color: "DBEAFE",
    fontSize: 17,
    fit: "shrink",
  });

  slide.addText("Generated by CortexAI", {
    x: 0,
    y: 6.9,
    w: 13.333,
    h: 0.25,
    align: "center",
    color: "BFDBFE",
    fontSize: 10,
  });
};

const addContentSlide = (ppt, title, points, page, total) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.white,
  };

  slide.addText(title, {
    x: 0.6,
    y: 0.35,
    w: 11.8,
    h: 0.5,
    fontSize: 24,
    bold: true,
    color: COLORS.primary,
    fit: "shrink",
  });

  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 0.98,
    w: 12,
    h: 0,
    line: {
      color: COLORS.border,
      width: 1.2,
    },
  });

  const visiblePoints = points.slice(0, 6);

  visiblePoints.forEach((point, index) => {
    const y = 1.25 + index * 0.82;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y,
      w: 12,
      h: 0.64,
      rectRadius: 0.08,
      fill: {
        color: index % 2 === 0 ? "EFF6FF" : COLORS.light,
      },
      line: {
        color: COLORS.border,
        width: 0.6,
      },
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.93,
      y: y + 0.25,
      w: 0.12,
      h: 0.12,
      fill: {
        color: COLORS.primary,
      },
      line: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(point), {
      x: 1.2,
      y: y + 0.08,
      w: 11.1,
      h: 0.48,
      fontSize: 15,
      color: COLORS.text,
      valign: "mid",
      breakLine: false,
      fit: "shrink",
      margin: 0.03,
    });
  });

  slide.addText(`${page}/${total}`, {
    x: 12.1,
    y: 6.9,
    w: 0.6,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
    align: "right",
  });

  slide.addText("CortexAI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
  });
};

const addThankYou = (ppt) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.secondary,
  };

  slide.addText("Thank You", {
    x: 0,
    y: 2.2,
    w: 13.333,
    h: 0.8,
    align: "center",
    fontSize: 30,
    color: COLORS.white,
    bold: true,
  });

  slide.addText("Generated by CortexAI", {
    x: 0,
    y: 6.9,
    w: 13.333,
    h: 0.2,
    align: "center",
    fontSize: 10,
    color: "94A3B8",
  });
};